// Writes components/standee/metrics.ts from the font files in assets/fonts.
// The standee layout (wrapping, centring) runs in the browser and on the server
// with the same numbers, so it needs advance widths without loading a font.
// Run again when a font file changes:  node scripts/gen-standee-metrics.mjs
import fontkit from "@pdf-lib/fontkit";
import { readFileSync, writeFileSync } from "node:fs";

const FACES = {
  fraunces700: "Fraunces-Bold",
  manrope600: "Manrope-SemiBold",
  manrope800: "Manrope-ExtraBold",
  dmsans400: "DMSans-Regular",
  dmsans700: "DMSans-Bold",
  nunito400: "Nunito-Regular",
  nunito700: "Nunito-Bold",
  indic400: "NotoSansDevanagari-Regular",
  indic700: "NotoSansDevanagari-Bold",
};

// Printable ASCII plus the punctuation shop names and headlines use.
const CODES = [];
for (let c = 32; c <= 126; c++) CODES.push(c);
CODES.push(0xb7, 0x2013, 0x2014, 0x2018, 0x2019, 0x201c, 0x201d, 0x2026, 0x20b9, 0xe9, 0xe8, 0xe0, 0xf1);

const round = (n) => Math.round(n * 10000) / 10000;
let out = `// Generated by scripts/gen-standee-metrics.mjs from assets/fonts. Do not edit.
// Advance widths and line metrics in em (1 = the font size), per face.
export type FaceMetrics = { asc: number; desc: number; def: number; adv: Record<number, number> };

export const METRICS: Record<string, FaceMetrics> = {\n`;
for (const [id, file] of Object.entries(FACES)) {
  const font = fontkit.create(readFileSync(new URL(`../assets/fonts/${file}.ttf`, import.meta.url)));
  const upm = font.unitsPerEm;
  const adv = {};
  for (const code of CODES) {
    const g = font.glyphForCodePoint(code);
    if (g && g.id !== 0) adv[code] = round(g.advanceWidth / upm);
  }
  const widths = Object.values(adv);
  const def = round(widths.reduce((a, b) => a + b, 0) / widths.length);
  out += `  ${id}: { asc: ${round(font.ascent / upm)}, desc: ${round(-font.descent / upm)}, def: ${id.startsWith("indic") ? 0.62 : def}, adv: ${JSON.stringify(adv)} },\n`;
}
out += "};\n";
writeFileSync(new URL("../components/standee/metrics.ts", import.meta.url), out);
console.log("wrote components/standee/metrics.ts");
